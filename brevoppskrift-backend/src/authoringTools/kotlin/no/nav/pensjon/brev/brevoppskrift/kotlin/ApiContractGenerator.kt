package no.nav.pensjon.brev.brevoppskrift.kotlin

import com.fasterxml.jackson.annotation.JsonSubTypes
import com.fasterxml.jackson.databind.JsonNode
import no.nav.pensjon.brev.brevoppskrift.draftObjectMapper
import java.io.File
import java.math.BigDecimal
import java.time.Instant
import java.util.UUID
import kotlin.reflect.KClass
import kotlin.reflect.KType
import kotlin.reflect.full.memberProperties
import kotlin.reflect.full.primaryConstructor
import kotlin.reflect.jvm.jvmErasure
import kotlin.reflect.full.withNullability

/** The model is the source of truth. No parallel handwritten DTO/TS/schema declarations. */
fun main(args: Array<String>) {
    require(args.size == 3) { "Usage: ApiContractGenerator <class-directories> <typescript> <openapi>" }
    val classes = discoverApiRoots(args[0].split(File.pathSeparator).map { File(it) })
    val contract = ApiContractGenerator().generate(classes)
    val typescript = File(args[1])
    typescript.parentFile.mkdirs()
    typescript.writeText(contract.typescript)
    val openapi = File(args[2])
    openapi.parentFile.mkdirs()
    draftObjectMapper.writerWithDefaultPrettyPrinter().writeValue(openapi, contract.openapi)
}

private const val BACKEND_PACKAGE = "no.nav.pensjon.brev.brevoppskrift"
private val envelopeRoots = setOf(
    "$BACKEND_PACKAGE.Capabilities",
    "$BACKEND_PACKAGE.ValidationResult",
    "$BACKEND_PACKAGE.auth.DraftUser",
    "$BACKEND_PACKAGE.integrasjoner.PrJob",
    "$BACKEND_PACKAGE.integrasjoner.AiRequest",
    "$BACKEND_PACKAGE.integrasjoner.AiResult",
)

/** Include API envelopes without exporting service wiring, database configuration or compiler snapshots. */
fun discoverApiRoots(directories: List<File>): List<KClass<*>> =
    directories.flatMap { root ->
        root.walkTopDown().filter { it.isFile && it.extension == "class" && '$' !in it.name }
            .map { it.relativeTo(root).path.removeSuffix(".class").replace(File.separatorChar, '.') }
            .filter {
                it in envelopeRoots || it.startsWith("$BACKEND_PACKAGE.model.") ||
                    (it.startsWith("$BACKEND_PACKAGE.api.") && it != "$BACKEND_PACKAGE.api.AuthoringDependencies") ||
                    (it.startsWith("$BACKEND_PACKAGE.lagring.") && it != "$BACKEND_PACKAGE.lagring.DatabaseConfig")
            }
            .filter { !it.endsWith("Kt") }
            .map { Class.forName(it).kotlin }
            .filter { it.isData || it.isSealed || it.java.isEnum }
            .toList()
    }.distinctBy { it.qualifiedName }.sortedBy { it.qualifiedName }

data class GeneratedContract(val typescript: String, val openapi: Map<String, Any>)

class ApiContractGenerator {
    private val declarations = linkedMapOf<String, String>()
    private val schemas = linkedMapOf<String, Any>()

    fun generate(roots: List<KClass<*>>): GeneratedContract {
        declarations.clear()
        schemas.clear()
        roots.forEach { register(it) }
        val text = "// Generated by :brevoppskrift-backend:generateAuthoringApi. Do not edit.\n\n" +
            "export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };\n\n" +
            declarations.toSortedMap().values.joinToString("\n\n") + "\n"
        return GeneratedContract(text, mapOf(
            "openapi" to "3.1.0",
            "info" to mapOf("title" to "Brevoppskrift authoring model", "version" to "1"),
            "paths" to emptyMap<String, Any>(),
            "components" to mapOf("schemas" to schemas.toSortedMap()),
        ))
    }

    private fun name(clazz: KClass<*>): String = clazz.java.enclosingClass?.simpleName.orEmpty() + requireNotNull(clazz.simpleName)
    private fun reference(clazz: KClass<*>): Map<String, String> = mapOf("\$ref" to "#/components/schemas/${name(clazz)}")
    private fun register(clazz: KClass<*>) {
        val name = name(clazz)
        if (name in declarations) return
        declarations[name] = "" // Recursive DraftBaseline / AttachmentCopy.
        if (clazz.java.isEnum) {
            val values = clazz.java.enumConstants.map { (it as Enum<*>).name }
            declarations[name] = "export type $name = ${values.joinToString(" | ") { quote(it) }};"
            schemas[name] = mapOf("type" to "string", "enum" to values)
            return
        }
        val subtypes = clazz.java.getAnnotation(JsonSubTypes::class.java)?.value
        if (subtypes != null) {
            subtypes.forEach { register(it.value) }
            declarations[name] = "export type $name = ${subtypes.joinToString(" | ") { name(it.value) }};"
            schemas[name] = mapOf(
                "oneOf" to subtypes.map { reference(it.value) },
                "discriminator" to mapOf("propertyName" to "type", "mapping" to subtypes.associate { it.name to "#/components/schemas/${name(it.value)}" }),
            )
            return
        }
        val parent = clazz.java.interfaces.map { it.kotlin }.firstOrNull { it.java.isAnnotationPresent(JsonSubTypes::class.java) }
        val discriminator = parent?.java?.getAnnotation(JsonSubTypes::class.java)?.value?.find { it.value == clazz }?.name
        val properties = linkedMapOf<String, Any>()
        val required = mutableListOf<String>()
        val lines = mutableListOf<String>()
        if (discriminator != null) {
            properties["type"] = mapOf("type" to "string", "const" to discriminator)
            required.add("type")
            lines.add("  type: ${quote(discriminator)};")
        }
        val parameters = clazz.primaryConstructor?.parameters.orEmpty().associateBy { it.name }
        val kotlinProperties = clazz.memberProperties.associateBy { it.name }
        val description = draftObjectMapper.serializationConfig.introspect(draftObjectMapper.typeFactory.constructType(clazz.java))
        description.findProperties().filter { it.couldSerialize() }.forEach { property ->
            val kotlinProperty = requireNotNull(kotlinProperties[property.internalName]) {
                "Serializable property ${clazz.qualifiedName}.${property.name} has no Kotlin property type."
            }
            val parameter = parameters[property.internalName]
            val type = kotlinProperty.returnType
            val optional = parameter?.isOptional == true
            if (!optional) required.add(property.name)
            properties[property.name] = schema(type) + if (parameter == null) mapOf("readOnly" to true) else emptyMap()
            lines.add("  ${if (parameter == null) "readonly " else ""}${quote(property.name)}${if (optional) "?" else ""}: ${typescript(type)};")
        }
        declarations[name] = "export interface $name {\n${lines.joinToString("\n")}\n}"
        schemas[name] = mapOf("type" to "object", "properties" to properties, "required" to required, "additionalProperties" to false)
    }

    private fun typescript(type: KType): String {
        val clazz = type.jvmErasure
        if (clazz.isValue) return typescript(underlying(type))
        val result = when {
            clazz == String::class || clazz == Instant::class || clazz == UUID::class -> "string"
            clazz == Boolean::class -> "boolean"
            clazz in setOf(Int::class, Long::class, Double::class, Float::class, BigDecimal::class) -> "number"
            JsonNode::class.java.isAssignableFrom(clazz.java) -> "JsonValue"
            Map::class.java.isAssignableFrom(clazz.java) -> {
                val key = requireNotNull(type.arguments[0].type)
                val value = requireNotNull(type.arguments[1].type)
                if (key.jvmErasure.java.isEnum) "Partial<Record<${typescript(key)}, ${typescript(value)}>>" else "Record<string, ${typescript(value)}>"
            }
            Collection::class.java.isAssignableFrom(clazz.java) -> "Array<${typescript(requireNotNull(type.arguments[0].type))}>"
            else -> { register(clazz); name(clazz) }
        }
        return result + if (type.isMarkedNullable) " | null" else ""
    }

    private fun schema(type: KType): Map<String, Any> {
        val clazz = type.jvmErasure
        if (clazz.isValue) return schema(underlying(type))
        val result: Map<String, Any> = when {
            clazz == String::class -> mapOf("type" to "string")
            clazz == Instant::class -> mapOf("type" to "string", "format" to "date-time")
            clazz == UUID::class -> mapOf("type" to "string", "format" to "uuid")
            clazz == Boolean::class -> mapOf("type" to "boolean")
            clazz in setOf(Int::class, Long::class) -> mapOf("type" to "integer")
            clazz in setOf(Double::class, Float::class, BigDecimal::class) -> mapOf("type" to "number")
            JsonNode::class.java.isAssignableFrom(clazz.java) -> emptyMap()
            Map::class.java.isAssignableFrom(clazz.java) -> mapOf("type" to "object", "additionalProperties" to schema(requireNotNull(type.arguments[1].type)))
            Collection::class.java.isAssignableFrom(clazz.java) -> mapOf("type" to "array", "items" to schema(requireNotNull(type.arguments[0].type)))
            else -> { register(clazz); reference(clazz) }
        }
        return if (type.isMarkedNullable) mapOf("anyOf" to listOf(result, mapOf("type" to "null"))) else result
    }

    private fun quote(value: String): String = draftObjectMapper.writeValueAsString(value)

    private fun underlying(type: KType): KType =
        requireNotNull(type.jvmErasure.primaryConstructor).parameters.single().type.withNullability(type.isMarkedNullable)
}
